export function getTeamDisplay(code) {
	const normalizedCode = (code || '').trim().toUpperCase()
	const [name, logoCode] = teamConfig[normalizedCode] || [normalizedCode || 'Unknown team', null]
	return {
		code: normalizedCode,
		name,
		logo: logoCode ? `https://a.espncdn.com/i/teamlogos/nba/500/${logoCode}.png` : null,
	}
}
