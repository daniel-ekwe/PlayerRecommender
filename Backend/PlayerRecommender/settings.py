# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

DATABASE_ENGINE = os.getenv(
    'DATABASE_ENGINE',
    'mssql' if os.getenv('WEBSITE_SITE_NAME') else 'sqlite',
).lower()
